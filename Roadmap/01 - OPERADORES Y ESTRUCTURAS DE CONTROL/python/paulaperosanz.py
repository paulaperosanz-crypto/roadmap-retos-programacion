# Operadores aritméticos
print(f"Suma: 10 + 3 = {10 + 3}")
print(f"Resta: 10 - 3 = {10 - 3}")
print(f"Multiplicación: 10 * 3 = {10 * 3}")
print(f"División: 10 / 3 = {10 / 3}")
print(f"División entera: 10 // 3 = {10 // 3}")
print(f"Módulo: 10 % 3 = {10 % 3}")
print(f"Potencia: 10 ** 3 = {10 ** 3}")

# Operadores de comparación
print("Igualdad: 10 == 3 es {10 == 3}")
print("Desigualdad: 10 != 3 es {10 != 3}")
print("Mayor que: 10 > 3 es {10 > 3}")
print("Menor que: 10 < 3 es {10 < 3}")
print("Mayor o igual que: 10 >= 3 es {10 >= 3}")
print("Menor o igual que: 10 <= 3 es {10 <= 3}")

# Operadores lógicos
print("AND: 3 + 4 = 8 and 2 - 7 = 2 es {3 + 4 = 8 and 2 - 7 = 2}")
print("OR: 3 + 4 = 8 or 2 - 7 = 2 es {3 + 4 = 8 or 2 - 7 = 2}")
print("NOT: 3 + 4 = 8 not 2 - 7 = 2 es {3 + 4 = 8 not 2 - 7 = 2}")

# Operadores de asignación
pepinillos = 1  # asignación (ahora su valor es 1)
print(pepinillos)
pepinillos += 4  # suma y asignación (ahora su valor es 5)
print(pepinillos)
pepinillos -= 1  # resta y asignación (ahora su valor es 4)
print(pepinillos)
pepinillos *= 3  # multiplicación y asignación (ahora su valor es 12)
print(pepinillos)
pepinillos /= 2  # división y asignación (ahora su valor es 6)
print(pepinillos)
pepinillos %= 2  # módulo y asignación (ahora su valor es 0)
print(pepinillos)
pepinillos **= 2  # exponencia y asignación (ahora su valor es 0)
print(pepinillos)
pepinillos //= 2  # división entera y asignación (ahora su valor es 0)
print(pepinillos)

